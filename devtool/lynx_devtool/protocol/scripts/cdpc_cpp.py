"""Lynx C++ spellings for CDPC graph v1 and object-root MethodContract."""
import hashlib
import json
import re

ADAPTER_VERSION = 1
TYPES = {name: name.title() for name in (
    'null', 'boolean', 'integer', 'number', 'string', 'object', 'array', 'any')}


def literal(value):
    # Three-digit octal escapes cannot absorb following digits and preserve UTF-8
    # and embedded NUL bytes. Explicit lengths retain the complete string_view.
    data = value.encode('utf-8')
    quoted = ''.join('\\'+chr(b) if b in (34,92) else chr(b) if 32 <= b < 127
                     else f'\\{b:03o}' for b in data)
    return f'std::string_view{{"{quoted}", {len(data)}}}'


def generate(graph):
    if graph.get('version') != 1:
        raise ValueError('Lynx C++ emitter requires descriptor graph version 1')
    nodes = graph['nodes']
    selected, omitted, symbols, used = [], [], {}, set()

    def resolve(index):
        seen = set()
        while 'ref' in nodes[index]:
            if index in seen:
                raise ValueError('reference-only cycle in descriptor graph')
            seen.add(index)
            index = nodes[index]['ref']
        return nodes[index]

    def visit(index, found):
        if index in found:
            return
        found.add(index)
        node = nodes[index]
        if 'ref' in node:
            resolve(index)
            visit(node['ref'], found)
            return
        kinds = node['types']
        if not kinds or any(kind not in TYPES for kind in kinds):
            raise ValueError('unsupported schema type')
        if 'any' in kinds and (kinds != ['any'] or set(node) != {'types'}):
            raise ValueError('native any cannot contain union alternatives or constraints')
        if 'array' in kinds and 'items' not in node:
            raise ValueError('array requires items')
        if 'enum' in node and (not node['enum'] or 'string' not in kinds):
            raise ValueError('enum requires nonempty string choices')
        for prop in node.get('properties', []):
            visit(prop['schema'], found)
        for field in ('items', 'values'):
            if field in node:
                visit(node[field], found)

    for name in graph['unsupported']['methods']:
        omitted.append({'name':name, 'reason':'unsupported contract; see contract diagnostics'})
    for entry in graph['methods']:
        name = entry['name']
        try:
            if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*\.[A-Za-z][A-Za-z0-9_]*', name):
                raise ValueError('method cannot be represented as a C++ identifier')
            for field in ('params', 'returns'):
                if resolve(entry[field]).get('types') != ['object']:
                    raise ValueError(f'{field} root must be exactly object for MethodContract')
            found = set()
            visit(entry['params'], found)
            visit(entry['returns'], found)
        except ValueError as error:
            omitted.append({'name':name, 'reason':str(error)})
            continue
        domain, method = name.split('.')
        symbol = 'k' + domain + method[0].upper() + method[1:]
        if symbol in symbols:
            raise ValueError(f'C++ symbol collision: {symbols[symbol]} and {name} map to {symbol}')
        symbols[symbol] = name
        selected.append((entry, symbol))
        used |= found

    fingerprint = hashlib.sha256(json.dumps(graph, sort_keys=True, ensure_ascii=False,
                                            allow_nan=False).encode()).hexdigest()
    guard = 'LYNX_DEVTOOL_CDPC_GENERATED_' + fingerprint[:16].upper() + '_H_'
    tool_version = graph['generator']['version']
    lines = ['// Copyright 2026 The Lynx Authors. All rights reserved.',
             '// Licensed under the Apache License Version 2.0 that can be found in the',
             '// LICENSE file in the root directory of this source tree.', '//',
             '// Generated by `tools/cdpc runtime write`. Do not edit by hand.',
             f'// CDPC {tool_version}; descriptor graph v1; Lynx emitter v{ADAPTER_VERSION}.',
             f'// Input graph SHA-256: {fingerprint}', '', f'#ifndef {guard}', f'#define {guard}', '',
             '#include <array>', '#include "cdpc/contract.h"', '',
             'namespace lynx::devtool::cdpc::methods {', 'namespace detail {']
    lines += [f'extern const Schema kSchema{i};' for i in sorted(used)]

    def ptr(index):
        return f'&kSchema{index}' if index is not None else 'nullptr'

    for i in sorted(used):
        node = nodes[i]
        if 'ref' in node:
            lines.append(f'inline constexpr Schema kSchema{i} = Schema::Ref({ptr(node["ref"])});')
            continue
        props, enums = node.get('properties', []), node.get('enum', [])
        if props:
            lines.append(f'inline constexpr Property kProperties{i}[] = {{')
            for prop in props:
                lines.append(f'    {{{literal(prop["name"])}, {ptr(prop["schema"])}, {str(prop["optional"]).lower()}}},')
            lines.append('};')
        if enums:
            lines.append(f'inline constexpr std::string_view kEnum{i}[] = {{')
            lines += [f'    {literal(value)},' for value in enums]
            lines.append('};')
        types = ' | '.join('Type::'+TYPES[k] for k in node['types'])
        shape = 'ObjectShape::Open' if node.get('open') else 'ObjectShape::Fixed'
        lines += [f'inline constexpr Schema kSchema{i} = {{', f'    {types}, {shape},',
                  f'    {"kProperties"+str(i) if props else "nullptr"}, {len(props)},',
                  f'    {ptr(node.get("items"))}, {ptr(node.get("values"))}, nullptr,',
                  f'    {"kEnum"+str(i) if enums else "nullptr"}, {len(enums)}}};']
    lines += ['}  // namespace detail', '']
    for entry, symbol in selected:
        lines += [f'inline constexpr MethodContract {symbol} = {{',
                  f'    {literal(entry["name"])}, &detail::kSchema{entry["params"]},',
                  f'    &detail::kSchema{entry["returns"]}}};']
    lines += ['', f'inline constexpr std::array<MethodContract, {len(selected)}> kContracts = {{']
    lines += [f'    {symbol},' for _,symbol in selected]
    lines += ['};', '', 'constexpr const MethodContract* Find(std::string_view name) {',
              '  for (const auto& contract : kContracts) {',
              '    if (contract.name == name) return &contract;',
              '  }', '  return nullptr;', '}', '',
              '}  // namespace lynx::devtool::cdpc::methods', '', f'#endif  // {guard}', '']
    report = {'version':1, 'generator':{'tool_version':tool_version, 'adapter_version':ADAPTER_VERSION},
              'input_graph_sha256':fingerprint, 'methods':[e['name'] for e,_ in selected],
              'omitted':sorted(omitted,key=lambda item:item['name'])}
    return '\n'.join(lines), report
