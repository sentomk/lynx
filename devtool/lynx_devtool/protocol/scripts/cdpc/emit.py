"""Deterministic manifest v2 and contract JSON emission."""
import difflib
import json
import os
import tempfile
import yaml
from cdpc.model import Diagnostic
from cdpc.schema import references, example_request


def contract_data(contract):
    data = {'version': 2, 'types': {}, 'methods': {}, 'events': {}, 'examples': [],
            'unsupported': {'methods': [], 'events': []}}
    def include(schema):
        for ref in references(schema):
            if ref not in data['types']:
                data['types'][ref] = contract.types[ref]
                include(contract.types[ref])
    for entry in sorted(contract.entries.values(), key=lambda entry: (entry.name, entry.kind)):
        if not entry.supported:
            data['unsupported']['methods' if entry.kind == 'method' else 'events'].append(entry.name)
            continue
        out = {'params': entry.params}
        include(entry.params)
        if entry.kind == 'method':
            out['returns'] = entry.returns
            include(entry.returns)
        data['methods' if entry.kind == 'method' else 'events'][entry.name] = out
        for example in entry.examples:
            if isinstance(example, dict):
                if entry.document.get('capture') == 'safe' and 'request' in example:
                    example = {**example, 'request': example_request(example['request'])}
                event = example.get('event', example.get('response'))
                if isinstance(event, dict) and 'method' in event and 'id' not in event:
                    dependency = contract.get('event', event['method'])
                    if dependency is None or not dependency.supported:
                        continue
                data['examples'].append({'entry': entry.name, **example})
    return data


def manifest(repo, contract, inventory):
    previous = yaml.safe_load(repo.manifest.read_text()) if repo.manifest.exists() else {}
    history = {}
    for domain in (previous or {}).get('domains', []):
        for entry in domain.get('methods', []):
            history[domain['name'] + '.' + entry['name']] = str(entry['since'])
    lines = ['# Copyright 2026 The Lynx Authors. All rights reserved.',
             '# Licensed under the Apache License Version 2.0 that can be found in the',
             '# LICENSE file in the root directory of this source tree.', '#',
             '# Generated by `tools/cdpc write`. Do not edit by hand.', '',
             'version: 2', 'generatedFrom:', '  chromeDevToolsProtocol: cdp_upstream/protocol.json',
             'upstreamRoot: https://chromedevtools.github.io/devtools-protocol/tot',
             'externalReferences:', '  v8:', '    displayName: V8',
             '    cdpRoot: https://chromedevtools.github.io/devtools-protocol/1-3', 'domains:']
    standard_domains = {d['domain'] for d in contract.upstream_raw.get('domains', [])}
    for domain in sorted({name.split('.')[0] for name in inventory.methods}):
        if domain not in inventory.scopes:
            raise ValueError(f'methods found for unregistered domain {domain}')
        lines += [f'  - name: {domain}', f'    origin: {"standard" if domain in standard_domains else "lynx-extension"}',
                  f'    scope: {inventory.scopes[domain]}', '    methods:']
        for name, registration in sorted(inventory.methods.items()):
            if name.split('.')[0] != domain:
                continue
            origin = 'standard' if 'method:' + name in contract.upstream_entries else 'lynx-extension'
            since = history.get(name, inventory.version)
            lines += [f'      - name: {name.split(".")[1]}', f'        origin: {origin}',
                      f"        since: '{since}'", f'        source: {registration.file}']
    return '\n'.join(lines) + '\n'


def generate(repo, contract, inventory):
    return {repo.manifest: manifest(repo, contract, inventory),
            repo.protocol / 'cdp_contract.generated.json': json.dumps(contract_data(contract), indent=2, sort_keys=True, ensure_ascii=False, allow_nan=False) + '\n'}


def check(repo, outputs):
    return [Diagnostic(repo.relative(path), 1, 'E301', 'generated file is missing or stale; run tools/cdpc write')
            for path, text in outputs.items() if not path.exists() or path.read_text() != text]


def write(outputs, dry_run=False, print_diff=True):
    updated = []
    for path, text in outputs.items():
        before = path.read_text() if path.exists() else ''
        if before == text:
            continue
        updated.append(str(path))
        if dry_run:
            if print_diff:
                print(''.join(difflib.unified_diff(before.splitlines(True), text.splitlines(True), fromfile=str(path), tofile=str(path))), end='')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            fd, temporary = tempfile.mkstemp(dir=path.parent, prefix='.' + path.name)
            try:
                with os.fdopen(fd, 'w', encoding='utf-8') as out:
                    out.write(text)
                os.replace(temporary, path)
            finally:
                if os.path.exists(temporary):
                    os.unlink(temporary)
    return updated
