"""Generate C++ protocol types for domains marked `codegen: typed`.

A Lynx-extension domain generates every entry in its docs. A standard domain
generates the upstream methods and events listed in cdp_support.yaml, with
deviations and docs additions applied, plus its Lynx-extension docs entries.

For each typed domain the generator emits, in
`lynx::devtool::protocol::<domain_snake_case>`:

- `<Method>Params` / `<Method>Result` structs for methods with fields,
  and one struct per event named after the event.
- `bool Decode(const Json::Value& params, <Method>Params*, std::string* error)`
- `Json::Value Encode(const <Method>Result&)` for the result object.
- `Json::Value Encode(const <Event>&)` for the complete event message.

Types referenced with `$ref` are generated once, in the namespace of the
domain that defines them, for example `protocol::dom::Node`. Only types
reachable from typed entries are generated. Primitive and array types become
aliases (`using NodeId = int64_t;`), string enums also get `<Type>Enum::k...`
constants, and objects with properties become structs.

Recursive types: a struct can only hold a complete type by value, so value
edges (direct, optional and map members) inside a strongly connected
component become `cdp::Box<T>`. `std::vector<T>` members accept incomplete
element types and stay unboxed. Structs are emitted in dependency order.

On top of the types, the dispatch layer adds `<Method>Responder` aliases, a
`Backend` interface with one pure virtual function per method, and an `Agent`
that decodes params and calls the Backend. The dispatch layer only depends on
the types, so it can be dropped without touching them.

Type mapping: string -> std::string, integer -> int64_t, number -> double,
boolean -> bool, objects with fields -> structs, `a.<key>` maps ->
std::map<std::string, T>, arrays -> std::vector<T>, optional fields ->
std::optional<T>. `any`, unions and objects without fields are stored as
Json::Value. String enums and union kinds are checked on decode, including
inside arrays and maps.

Descriptions and examples never reach C++, so docs-only edits keep the
generated bytes unchanged.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Callable, Optional

from cdpc import contract
from cdpc.contract import Schema
from cdpc.repo import CdpcError


CPP_KEYWORDS = frozenset(
    {
        "alignas", "alignof", "and", "asm", "auto", "bool", "break", "case",
        "catch", "char", "class", "const", "constexpr", "continue", "default",
        "delete", "do", "double", "else", "enum", "explicit", "export",
        "extern", "false", "float", "for", "friend", "goto", "if", "inline",
        "int", "long", "mutable", "namespace", "new", "noexcept", "not",
        "nullptr", "operator", "or", "private", "protected", "public",
        "register", "return", "short", "signed", "sizeof", "static",
        "struct", "switch", "template", "this", "throw", "true", "try",
        "typedef", "typeid", "typename", "union", "unsigned", "using",
        "virtual", "void", "volatile", "while",
    }
)
KIND_BITS = {
    "string": "cdp::kString",
    "integer": "cdp::kInteger",
    "number": "cdp::kNumber",
    "boolean": "cdp::kBoolean",
    "object": "cdp::kObject",
    "array": "cdp::kArray",
    "null": "cdp::kNull",
}
SCALARS = {
    "string": "std::string",
    "integer": "int64_t",
    "number": "double",
    "boolean": "bool",
}

# (C++ value expression, C++ path expression, nesting depth) -> bool expression.
CheckBuilder = Callable[[str, str, int], str]
TypeKey = tuple[str, str]  # (namespace, name)


class CodegenError(CdpcError):
    pass


def snake_case(name: str) -> str:
    text = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name)
    return text.lower()


def upper_camel(name: str) -> str:
    return name[:1].upper() + name[1:]


def member_name(wire: str) -> str:
    name = snake_case(wire)
    return name + "_" if name in CPP_KEYWORDS else name


def enum_constant(value: str) -> str:
    parts = [part for part in re.split(r"[^A-Za-z0-9]+", value) if part]
    return "k" + "".join(upper_camel(part) for part in parts)


# ---------------------------------------------------------------------------
# Type expressions


@dataclass(eq=False)
class _Expr:
    """A C++ type in a field, kept structured until boxing is decided."""

    kind: str  # "scalar", "vector", "map", "struct", "alias"
    cpp: str = ""  # scalar spelling
    inner: Optional["_Expr"] = None  # vector / map element
    key: Optional[TypeKey] = None  # struct / alias
    check: Optional[CheckBuilder] = None  # scalar constraint, such as an enum
    boxed: bool = False  # struct reference held through cdp::Box


def _qualified(key: TypeKey) -> str:
    return f"{key[0]}::{key[1]}"


def _render(expr: _Expr, namespace: str) -> str:
    """Spell |expr| for use inside |namespace|."""

    if expr.kind == "scalar":
        return expr.cpp
    if expr.kind == "vector":
        return f"std::vector<{_render(expr.inner, namespace)}>"
    if expr.kind == "map":
        return f"std::map<std::string, {_render(expr.inner, namespace)}>"
    name = expr.key[1] if expr.key[0] == namespace else _qualified(expr.key)
    return f"cdp::Box<{name}>" if expr.boxed else name


@dataclass
class _Alias:
    key: TypeKey
    target: _Expr
    enum: Optional[tuple[str, ...]] = None


@dataclass
class _Field:
    wire: str
    member: str
    expr: _Expr
    optional: bool


@dataclass
class _Struct:
    key: TypeKey
    comment: str
    fields: list[_Field] = field(default_factory=list)
    decode: bool = False
    encode: bool = False


class _TypeBuilder:
    """Builds structs and aliases for typed domains and their `$ref` closure."""

    def __init__(self, upstream: Optional[contract.Upstream]):
        self.upstream = upstream
        self.structs: dict[TypeKey, _Struct] = {}
        self.aliases: dict[TypeKey, _Alias] = {}
        self.owners: dict[TypeKey, str] = {}

    def _claim(self, key: TypeKey, where: str) -> None:
        if key in self.owners:
            raise CodegenError(
                f"{where}: generated type {_qualified(key)} also used by "
                f"{self.owners[key]}; set `typeName` to disambiguate"
            )
        self.owners[key] = where

    # Structs ---------------------------------------------------------------

    def struct(self, key: TypeKey, comment: str, schema: Schema, where: str) -> _Struct:
        self._claim(key, where)
        result = _Struct(key=key, comment=comment)
        # Register before building fields so self references resolve.
        self.structs[key] = result
        for wire, prop in (schema.properties or {}).items():
            expr = self.expr(
                prop.schema, key[0], key[1] + upper_camel(wire), f"{where}.{wire}"
            )
            result.fields.append(
                _Field(wire=wire, member=member_name(wire), expr=expr, optional=prop.optional)
            )
        return result

    # Expressions -----------------------------------------------------------

    def expr(self, schema: Schema, namespace: str, hint: str, where: str) -> _Expr:
        if schema.ref is not None:
            return self.ref(schema.ref, where)
        name = schema.type_name or hint
        kinds = schema.kinds
        if kinds == {"any"}:
            return _Expr("scalar", cpp="Json::Value")
        if len(kinds) == 1:
            kind = next(iter(kinds))
            if kind in SCALARS:
                return _Expr("scalar", cpp=SCALARS[kind], check=_enum_check(schema.enum))
            if kind == "object":
                if schema.properties and schema.additional is not None:
                    raise CodegenError(f"{where}: objects with both fields and <key> are not supported")
                if schema.properties is not None:
                    key = (namespace, name)
                    self.struct(key, f"{where}.", schema, where)
                    return _Expr("struct", key=key)
                if schema.additional is not None:
                    inner = self.expr(schema.additional, namespace, name + "Value", f"{where}.<key>")
                    return _Expr("map", inner=inner)
                return _Expr("scalar", cpp="Json::Value", check=_kinds_check(kinds))
            if kind == "array":
                if schema.items is None:
                    return _Expr("vector", inner=_Expr("scalar", cpp="Json::Value"))
                inner = self.expr(schema.items, namespace, name + "Item", f"{where}[]")
                return _Expr("vector", inner=inner)
        return _Expr("scalar", cpp="Json::Value", check=_kinds_check(kinds))

    def ref(self, ref: str, where: str) -> _Expr:
        domain, type_id = ref.split(".", 1)
        key = (snake_case(domain), type_id)
        if key in self.structs:
            return _Expr("struct", key=key)
        if key in self.aliases:
            return _Expr("alias", key=key)
        schema = self.upstream.types.get(ref) if self.upstream else None
        if schema is None:
            raise CodegenError(f"{where}: unresolved type reference {ref}")
        if schema.ref is not None:
            return self.ref(schema.ref, where)
        if schema.kinds == {"object"} and schema.properties is not None:
            self.struct(key, f"{ref}.", schema, ref)
            return _Expr("struct", key=key)
        self._claim(key, ref)
        alias = _Alias(key=key, target=_Expr("scalar", cpp="Json::Value"), enum=schema.enum)
        self.aliases[key] = alias
        alias.target = self.expr(schema, key[0], type_id, ref)
        return _Expr("alias", key=key)

    # Checks ------------------------------------------------------------------

    def check(self, expr: _Expr) -> Optional[CheckBuilder]:
        """Return the decode-time constraint of |expr|, or None."""

        if expr.kind == "scalar":
            return expr.check
        if expr.kind == "alias":
            return self.check(self.aliases[expr.key].target)
        if expr.kind in ("vector", "map"):
            inner = self.check(expr.inner)
            if inner is None:
                return None

            def each(value: str, path: str, depth: int) -> str:
                item, item_path = f"item{depth}", f"path{depth}"
                body = inner(item, item_path, depth + 1)
                return (
                    f"cdp::CheckEach({value}, {path}, [&](const auto& {item}, "
                    f"const std::string& {item_path}) {{ return {body}; }})"
                )

            return each
        return None  # Structs check their own fields when decoded.


def _enum_check(values: Optional[tuple[str, ...]]) -> Optional[CheckBuilder]:
    if values is None:
        return None
    listed = ", ".join(f'"{value}"' for value in values)
    return lambda value, path, depth: f"cdp::CheckEnum({value}, {path}, {{{listed}}}, error)"


def _kinds_check(kinds: frozenset[str]) -> CheckBuilder:
    bits = " | ".join(KIND_BITS[kind] for kind in sorted(kinds))
    return lambda value, path, depth: f"cdp::CheckKinds({value}, {path}, {bits}, error)"


# ---------------------------------------------------------------------------
# Struct graph: boxing and ordering


def _struct_refs(expr: _Expr, aliases: dict[TypeKey, _Alias], via_vector: bool = False):
    """Yield (struct expression, reached through a vector) for |expr|."""

    if expr.kind == "struct":
        yield expr, via_vector
    elif expr.kind == "vector":
        yield from _struct_refs(expr.inner, aliases, True)
    elif expr.kind == "map":
        yield from _struct_refs(expr.inner, aliases, via_vector)
    elif expr.kind == "alias":
        yield from _struct_refs(aliases[expr.key].target, aliases, via_vector)


def _edges(builder: _TypeBuilder):
    """Return (value edges, vector edges) between structs.

    Value edges need the target complete: direct, optional and map members.
    Vector edges do not, since std::vector accepts incomplete element types.
    Each value edge keeps its struct expression so it can be boxed in place,
    including when it is reached through an alias definition.
    """

    value: dict[TypeKey, list[tuple[TypeKey, _Expr]]] = {key: [] for key in builder.structs}
    vector: dict[TypeKey, list[TypeKey]] = {key: [] for key in builder.structs}
    for key, struct in builder.structs.items():
        for item in struct.fields:
            for ref, via_vector in _struct_refs(item.expr, builder.aliases):
                if via_vector:
                    vector[key].append(ref.key)
                else:
                    value[key].append((ref.key, ref))
    return value, vector


def _components(nodes: list[TypeKey], edges: dict[TypeKey, list[TypeKey]]) -> dict[TypeKey, int]:
    """Tarjan's strongly connected components; returns node -> component id."""

    index: dict[TypeKey, int] = {}
    low: dict[TypeKey, int] = {}
    stack: list[TypeKey] = []
    on_stack: set[TypeKey] = set()
    component: dict[TypeKey, int] = {}
    counter = [0, 0]

    def visit(node: TypeKey) -> None:
        index[node] = low[node] = counter[0]
        counter[0] += 1
        stack.append(node)
        on_stack.add(node)
        for target in edges[node]:
            if target not in index:
                visit(target)
                low[node] = min(low[node], low[target])
            elif target in on_stack:
                low[node] = min(low[node], index[target])
        if low[node] == index[node]:
            while True:
                member = stack.pop()
                on_stack.discard(member)
                component[member] = counter[1]
                if member == node:
                    break
            counter[1] += 1

    for node in nodes:
        if node not in index:
            visit(node)
    return component


def _box_and_order(builder: _TypeBuilder) -> list[_Struct]:
    value, vector = _edges(builder)
    nodes = list(builder.structs)  # creation order: entries first, then what they use
    component = _components(nodes, {key: [target for target, _ in value[key]] for key in nodes})
    for key in nodes:
        for target, ref in value[key]:
            if component[target] == component[key]:
                ref.boxed = True

    # Unboxed value dependencies must be defined first. Vector dependencies are
    # pulled in first too when that keeps the value order valid, so element
    # structs usually precede the structs holding them.
    ordered: list[_Struct] = []
    done: set[TypeKey] = set()
    active: set[TypeKey] = set()

    def emit(key: TypeKey) -> bool:
        if key in done:
            return True
        if key in active:
            return False
        active.add(key)
        for target, ref in value[key]:
            if not ref.boxed and not emit(target):
                active.discard(key)
                return False
        for target in vector[key]:
            emit(target)
        active.discard(key)
        done.add(key)
        ordered.append(builder.structs[key])
        return True

    for key in nodes:
        emit(key)
    return ordered


def _alias_order(builder: _TypeBuilder) -> list[_Alias]:
    ordered: list[_Alias] = []
    done: set[TypeKey] = set()

    def deps(expr: _Expr):
        if expr.kind == "alias":
            yield expr.key
        elif expr.inner is not None:
            yield from deps(expr.inner)

    def emit(key: TypeKey) -> None:
        if key in done:
            return
        done.add(key)
        for target in deps(builder.aliases[key].target):
            emit(target)
        ordered.append(builder.aliases[key])

    for key in sorted(builder.aliases):
        emit(key)
    return ordered


def _mark(builder: _TypeBuilder, expr: _Expr, decode: bool, encode: bool) -> None:
    if expr.kind == "struct":
        struct = builder.structs[expr.key]
        if (decode and not struct.decode) or (encode and not struct.encode):
            struct.decode = struct.decode or decode
            struct.encode = struct.encode or encode
            for item in struct.fields:
                _mark(builder, item.expr, decode, encode)
    elif expr.kind == "alias":
        _mark(builder, builder.aliases[expr.key].target, decode, encode)
    elif expr.inner is not None:
        _mark(builder, expr.inner, decode, encode)


# ---------------------------------------------------------------------------
# Domains


@dataclass
class _Command:
    key: str
    method: str  # UpperCamel C++ method name
    params: Optional[str]  # params struct, or None without param fields
    result: Optional[str]  # result struct, or None without result fields

    @property
    def responder(self) -> str:
        return f"{self.method}Responder"


@dataclass
class _Domain:
    name: str
    namespace: str
    commands: list[_Command] = field(default_factory=list)
    decoders: list[tuple[str, str]] = field(default_factory=list)  # (struct, entry key)
    result_encoders: list[tuple[str, str]] = field(default_factory=list)
    event_encoders: list[tuple[str, str, bool]] = field(default_factory=list)  # (struct, key, has fields)


@dataclass
class _Model:
    domains: list[_Domain]
    aliases: list[_Alias]
    structs: list[_Struct]
    builder: _TypeBuilder


def build_model(contracts: contract.ContractSet) -> _Model:
    builder = _TypeBuilder(contracts.upstream)
    domains = []
    for domain_name in sorted(contracts.typed_domains):
        namespace = snake_case(domain_name)
        domain = _Domain(name=domain_name, namespace=namespace)
        entries = contract.typed_entries(contracts, domain_name)
        for entry in (item for item in entries if item.kind == "method"):
            for section, schema in (("params", entry.parameters), ("result", entry.returns)):
                if schema is None or schema.kinds != {"object"} or schema.properties is None:
                    raise CodegenError(f"{entry.key}: root {section} is not supported by typed codegen")
            base = upper_camel(entry.name)
            command = _Command(key=entry.key, method=base, params=None, result=None)
            if entry.parameters.properties:
                key = (namespace, f"{base}Params")
                builder.struct(key, f"{entry.key} params.", entry.parameters, f"{entry.key}.params")
                _mark(builder, _Expr("struct", key=key), decode=True, encode=False)
                domain.decoders.append((key[1], entry.key))
                command.params = key[1]
            if entry.returns.properties:
                key = (namespace, f"{base}Result")
                builder.struct(key, f"{entry.key} result.", entry.returns, f"{entry.key}.result")
                _mark(builder, _Expr("struct", key=key), decode=False, encode=True)
                domain.result_encoders.append((key[1], entry.key))
                command.result = key[1]
            domain.commands.append(command)
        for entry in (item for item in entries if item.kind == "event"):
            key = (namespace, upper_camel(entry.name))
            struct = builder.struct(key, f"{entry.key} event.", entry.parameters, f"{entry.key}.params")
            _mark(builder, _Expr("struct", key=key), decode=False, encode=True)
            domain.event_encoders.append((key[1], entry.key, bool(struct.fields)))
        domains.append(domain)
    structs = _box_and_order(builder)
    return _Model(domains=domains, aliases=_alias_order(builder), structs=structs, builder=builder)


# ---------------------------------------------------------------------------
# Emission


def _blocks(items, namespace_of, render) -> list[str]:
    """Render |items| in order, opening a namespace block per run."""

    lines: list[str] = []
    current = None
    for item in items:
        namespace = namespace_of(item)
        if namespace != current:
            if current is not None:
                lines += [f"}}  // namespace {current}", ""]
            lines += [f"namespace {namespace} {{", ""]
            current = namespace
        lines += render(item)
    if current is not None:
        lines += [f"}}  // namespace {current}"]
    return lines


def _field_check(model: _Model, item: _Field) -> Optional[str]:
    check = model.builder.check(item.expr)
    if check is None:
        return None
    member = f"out->{item.member}"
    path = f'path + ".{item.wire}"'
    if item.optional:
        return f"!{member} || {check(f'*{member}', path, 0)}"
    return check(member, path, 0)


def _decode_signature(struct: _Struct) -> str:
    return (
        f"static bool DecodeValue(const Json::Value& in, const std::string& path, "
        f"{struct.key[1]}* out, std::string* error)"
    )


def _encode_signature(struct: _Struct) -> str:
    return f"static Json::Value EncodeValue(const {struct.key[1]}& value)"


def generate(
    contracts: contract.ContractSet,
    header_include: str,
    notice: list[str],
    root_namespace: str = "protocol",
) -> tuple[str, str]:
    model = build_model(contracts)
    guard = re.sub(r"[^A-Za-z0-9]", "_", header_include).upper() + "_"

    header = notice + [
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <cstdint>",
        "#include <map>",
        "#include <memory>",
        "#include <optional>",
        "#include <string>",
        "#include <vector>",
        "",
        '#include "devtool/base_devtool/native/public/cdp_codec.h"',
        '#include "devtool/base_devtool/native/public/cdp_domain_agent_base.h"',
        '#include "devtool/base_devtool/native/public/cdp_typed_responder.h"',
        '#include "third_party/jsoncpp/include/json/json.h"',
        "",
        "namespace lynx {",
        "namespace devtool {",
        f"namespace {root_namespace} {{",
    ]

    if model.structs:
        header += [""]
        header += _blocks(
            sorted(model.structs, key=lambda item: item.key),
            lambda item: item.key[0],
            lambda item: [f"struct {item.key[1]};"],
        )
    if model.aliases:
        header += [""]
        header += _blocks(model.aliases, lambda item: item.key[0], _render_alias)
    if model.structs:
        header += [""]
        header += _blocks(model.structs, lambda item: item.key[0], _render_struct)

    for domain in model.domains:
        header += ["", f"namespace {domain.namespace} {{", ""]
        for name, key in domain.decoders:
            header += [
                f"// Decodes {key} params. Unknown fields are ignored. On failure",
                "// returns false and sets |error| to an InvalidParams message.",
                f"bool Decode(const Json::Value& params, {name}* out, std::string* error);",
                "",
            ]
        for name, key in domain.result_encoders:
            header += [f"// Encodes the {key} result object.", f"Json::Value Encode(const {name}& result);", ""]
        for name, key, _ in domain.event_encoders:
            header += [f"// Encodes a complete {key} event message.", f"Json::Value Encode(const {name}& event);", ""]
        header += _dispatch_header(domain)
        header.append(f"}}  // namespace {domain.namespace}")

    source = notice + [
        f'#include "{header_include}"',
        "",
        "#include <utility>",
        "",
        '#include "devtool/base_devtool/native/public/cdp_error_code.h"',
        "",
        "namespace lynx {",
        "namespace devtool {",
        f"namespace {root_namespace} {{",
    ]

    coded = [item for item in model.structs if item.fields and (item.decode or item.encode)]
    if coded:
        # Declared up front so recursive structs can decode each other.
        source += [""]
        source += _blocks(
            coded,
            lambda item: item.key[0],
            lambda item: ([f"{_decode_signature(item)};"] if item.decode else [])
            + ([f"{_encode_signature(item)};"] if item.encode else []),
        )
        source += [""]
        source += _blocks(coded, lambda item: item.key[0], lambda item: _render_codecs(model, item))

    for domain in model.domains:
        source += ["", f"namespace {domain.namespace} {{"]
        for name, _ in domain.decoders:
            source += [
                "",
                f"bool Decode(const Json::Value& params, {name}* out, std::string* error) {{",
                '  return DecodeValue(params.isNull() ? cdp::EmptyObject() : params, "params", out, error);',
                "}",
            ]
        for name, _ in domain.result_encoders:
            source += ["", f"Json::Value Encode(const {name}& result) {{", "  return EncodeValue(result);", "}"]
        for name, key, has_fields in domain.event_encoders:
            source += [
                "",
                f"Json::Value Encode(const {name}& event) {{",
                "  Json::Value message(Json::objectValue);",
                f'  message["method"] = "{key}";',
            ]
            source += ['  message["params"] = EncodeValue(event);'] if has_fields else []
            source += ["  return message;", "}"]
        source += _dispatch_source(domain)
        source += ["", f"}}  // namespace {domain.namespace}"]

    footer = ["", f"}}  // namespace {root_namespace}", "}  // namespace devtool", "}  // namespace lynx"]
    header += footer + ["", f"#endif  // {guard}", ""]
    source += footer + [""]
    return "\n".join(header), "\n".join(source)


def _render_alias(alias: _Alias) -> list[str]:
    lines = []
    if alias.enum is not None:
        constants = {}
        for value in alias.enum:
            name = enum_constant(value)
            if name in constants:
                raise CodegenError(
                    f"{_qualified(alias.key)}: enum values {constants[name]!r} and "
                    f"{value!r} map to the same constant {name}"
                )
            constants[name] = value
        lines.append(f"namespace {alias.key[1]}Enum {{")
        lines += [f'inline constexpr char {name}[] = "{value}";' for name, value in constants.items()]
        lines.append(f"}}  // namespace {alias.key[1]}Enum")
    lines += [f"using {alias.key[1]} = {_render(alias.target, alias.key[0])};", ""]
    return lines


def _render_struct(struct: _Struct) -> list[str]:
    lines = [f"// {struct.comment}"]
    if not struct.fields:
        return lines + [f"struct {struct.key[1]} {{}};", ""]
    lines.append(f"struct {struct.key[1]} {{")
    for item in struct.fields:
        cpp = _render(item.expr, struct.key[0])
        if item.optional:
            cpp = f"std::optional<{cpp}>"
        lines.append(f"  {cpp} {item.member}{{}};")
    return lines + ["};", ""]


def _render_codecs(model: _Model, struct: _Struct) -> list[str]:
    lines = []
    if struct.decode:
        lines += [
            f"{_decode_signature(struct)} {{",
            "  if (!in.isObject()) {",
            '    return cdp::Fail(path, "expected object", error);',
            "  }",
        ]
        for item in struct.fields:
            lines += [
                f'  if (!cdp::DecodeField(in, "{item.wire}", path, &out->{item.member}, error)) {{',
                "    return false;",
                "  }",
            ]
            check = _field_check(model, item)
            if check:
                lines += [f"  if (!({check})) {{", "    return false;", "  }"]
        lines += ["  return true;", "}", ""]
    if struct.encode:
        lines += [f"{_encode_signature(struct)} {{", "  Json::Value out(Json::objectValue);"]
        lines += [f'  cdp::EncodeField(&out, "{item.wire}", value.{item.member});' for item in struct.fields]
        lines += ["  return out;", "}", ""]
    return lines


