# Dispatch layer


def _backend_signature(command: _Command, prefix: str = "") -> str:
    args = f"{prefix}{command.responder} responder"
    if command.params:
        args += f", {prefix}{command.params} params"
    return f"void {command.method}({args})"


def _dispatch_header(domain: _Domain) -> list[str]:
    lines = []
    for command in domain.commands:
        result = command.result or "cdp::Empty"
        lines.append(f"using {command.responder} = cdp::Responder<{result}>;")
    lines += [
        "",
        f"// Implemented by the {domain.name} domain. Params arrive decoded; each",
        "// method must reply through its responder.",
        "class Backend {",
        " public:",
        "  virtual ~Backend() = default;",
    ]
    lines += [f"  virtual {_backend_signature(command)} = 0;" for command in domain.commands]
    lines += [
        "};",
        "",
        f"// Dispatches {domain.name} methods to a Backend. Subclass it to filter",
        "// requests in PreDispatch.",
        "class Agent : public CDPDomainAgentBase {",
        " public:",
        "  explicit Agent(std::unique_ptr<Backend> backend);",
        "  ~Agent() override;",
        "",
        "  void CallMethod(const std::shared_ptr<CDPResponder>& responder,",
        "                  const Json::Value& message) override;",
        "",
        " protected:",
        "  // Runs before params are decoded. Return false after replying through",
        "  // |responder| to reject the request. Allows every request by default.",
        "  virtual bool PreDispatch(const std::string& method,",
        "                           const Json::Value& message,",
        "                           const std::shared_ptr<CDPResponder>& responder);",
        "",
        " private:",
        "  std::unique_ptr<Backend> backend_;",
        "};",
        "",
        "// Wraps |backend| in an Agent. Returns nullptr when |backend| is null.",
        "std::unique_ptr<CDPDomainAgentBase> CreateAgent(std::unique_ptr<Backend> backend);",
        "",
    ]
    return lines


def _dispatch_source(domain: _Domain) -> list[str]:
    lines = [
        "",
        "Agent::Agent(std::unique_ptr<Backend> backend) : backend_(std::move(backend)) {}",
        "",
        "Agent::~Agent() = default;",
        "",
        "bool Agent::PreDispatch(const std::string& method, const Json::Value& message,",
        "                        const std::shared_ptr<CDPResponder>& responder) {",
        "  return true;",
        "}",
        "",
        "void Agent::CallMethod(const std::shared_ptr<CDPResponder>& responder,",
        "                       const Json::Value& message) {",
        '  const std::string method = message["method"].asString();',
        "  if (!PreDispatch(method, message, responder)) {",
        "    return;",
        "  }",
    ]
    for command in domain.commands:
        lines.append(f'  if (method == "{command.key}") {{')
        if command.params:
            lines += [
                f"    {command.params} params;",
                "    std::string error;",
                '    if (!Decode(message["params"], &params, &error)) {',
                "      responder->SendError(CDPErrorCode::InvalidParams, error);",
                "      return;",
                "    }",
                f"    backend_->{command.method}({command.responder}(responder), std::move(params));",
            ]
        else:
            lines.append(f"    backend_->{command.method}({command.responder}(responder));")
        lines += ["    return;", "  }"]
    lines += [
        "  responder->SendError(CDPErrorCode::MethodNotFound,",
        """                       "'" + method + "' wasn't found");""",
        "}",
        "",
        "std::unique_ptr<CDPDomainAgentBase> CreateAgent(std::unique_ptr<Backend> backend) {",
        "  if (!backend) {",
        "    return nullptr;",
        "  }",
        "  return std::make_unique<Agent>(std::move(backend));",
        "}",
    ]
    return lines


@dataclass
class BackendMethod:
    key: str  # "Domain.method"
    method: str  # C++ method name
    args: str  # parameter list with types qualified from lynx::devtool


def backend_methods(
    contracts: contract.ContractSet, domain_name: str
) -> tuple[str, list[BackendMethod]]:
    """The C++ namespace and Backend methods of a typed domain."""

    domains = {domain.name: domain for domain in build_model(contracts).domains}
    if domain_name not in domains:
        raise CodegenError(
            f"{domain_name} is not a typed domain; typed domains: {', '.join(sorted(domains)) or 'none'}"
        )
    domain = domains[domain_name]
    prefix = f"protocol::{domain.namespace}::"
    methods = []
    for command in domain.commands:
        args = f"{prefix}{command.responder} responder"
        if command.params:
            args += f", {prefix}{command.params} params"
        methods.append(BackendMethod(command.key, command.method, args))
    return domain.namespace, methods
