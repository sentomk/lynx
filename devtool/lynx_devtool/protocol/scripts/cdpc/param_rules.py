"""Emit constant runtime parameter descriptors, never types or dispatch code."""
import json


def generate(contract, inventory):
    nodes, indices = [], {}

    def add(schema):
        key = json.dumps(schema, sort_keys=True)
        if key not in indices:
            indices[key] = len(nodes)
            nodes.append(schema)
            if 'ref' in schema:
                add(contract.types[schema['ref']])
            for _, prop in sorted(schema.get('properties', {}).items()):
                add(prop['schema'])
            for field in ('items', 'values'):
                if field in schema:
                    add(schema[field])
        return indices[key]

    methods = []
    for name in sorted(inventory.methods):
        entry = contract.get('method', name)
        if entry and entry.supported:
            methods.append((name, add(entry.params)))
    lines = ['// Copyright 2026 The Lynx Authors. All rights reserved.',
             '// Licensed under the Apache License Version 2.0 that can be found in the',
             '// LICENSE file in the root directory of this source tree.', '//',
             '// Generated by `tools/cdpc write`. Do not edit by hand.', '',
             '#include "devtool/base_devtool/native/public/cdp_param_utils.h"', '',
             '#include <algorithm>', '#include <iterator>', '',
             'namespace lynx {', 'namespace devtool {', 'namespace {']
    lines += [f'extern const CDPParamSchema kSchema{i};' for i in range(len(nodes))]

    def ptr(schema):
        return f'&kSchema{add(schema)}' if schema is not None else 'nullptr'

    for i, schema in enumerate(nodes):
        props = schema.get('properties', {})
        if props:
            lines.append(f'constexpr CDPParamProperty kProperties{i}[] = {{')
            for name, prop in sorted(props.items()):
                lines.append(f'    {{{json.dumps(name)}, {ptr(prop["schema"])}, {str(prop.get("optional", False)).lower()}}},')
            lines.append('};')
        enums = schema.get('enum', [])
        if 'enum' in schema:
            # Empty enums reject all strings; one sentinel keeps the array legal.
            lines.append(f'constexpr const char* kEnum{i}[] = {{' +
                         ', '.join(json.dumps(s) for s in enums or ['']) + '};')
        kinds = schema.get('type', 'any')
        if isinstance(kinds, str):
            kinds = [kinds]
        types = ' | '.join('CDPParamType::k' +
                          ('Map' if k == 'object' and 'values' in schema else k.title())
                          for k in kinds)
        ref = ptr(contract.types[schema['ref']]) if 'ref' in schema else 'nullptr'
        lines += [f'const CDPParamSchema kSchema{i} = {{',
                  f'    {types},',
                  f'    {"kProperties" + str(i) if props else "nullptr"}, {len(props)},',
                  f'    {ptr(schema.get("items"))}, {ptr(schema.get("values"))}, {ref},',
                  f'    {"kEnum" + str(i) if "enum" in schema else "nullptr"}, {len(enums)}}};']
    if methods:
        lines += ['constexpr CDPParamRuleSet kMethods[] = {']
        lines += [f'    {{{json.dumps(name)}, &kSchema{i}}},' for name, i in methods]
        lines += ['};']
    lines += ['}  // namespace', '',
              'const CDPParamRuleSet* FindCDPParamRules(std::string_view method) {']
    if methods:
        lines += ['  const auto* found = std::lower_bound(',
                  '      std::begin(kMethods), std::end(kMethods), method,',
                  '      [](const CDPParamRuleSet& rule, std::string_view name) {',
                  '        return rule.method < name;', '      });',
                  '  return found != std::end(kMethods) && found->method == method ? found',
                  '                                                                 : nullptr;']
    else:
        lines += ['  return nullptr;']
    lines += ['}', '', '}  // namespace devtool', '}  // namespace lynx', '']
    return '\n'.join(lines)
