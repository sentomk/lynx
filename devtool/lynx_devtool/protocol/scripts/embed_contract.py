"""Embed UTF-8 JSON with only the standard library and bounded C++ literals."""
import argparse
import json
from pathlib import Path
import re


def embed(data, symbol):
    if not re.fullmatch(r'[A-Za-z_]\w*', symbol):
        raise ValueError('invalid C++ symbol')
    json.loads(data)  # Fail the build on malformed input.
    def literal(chunk):
        return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34, 63, 92) else f'\\{b:03o}' for b in chunk) + '"'
    lines = ['// Generated by embed_contract.py. Do not edit.', '#include <string>', '#include <string_view>',
             'namespace lynx { namespace devtool { namespace protocol {', f'std::string_view {symbol}() {{',
             '  static const std::string data = [] {', '    std::string result;']
    for i in range(0, len(data), 4000):
        lines.append('    result += ' + literal(data[i:i+4000]) + ';')
    lines += ['    return result;', '  }();', '  return data;', '}', '} } }', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--symbol', default='ContractJson')
    args = parser.parse_args()
    result = embed(args.input.read_bytes(), args.symbol)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text() != result:
        args.output.write_text(result, encoding='utf-8')

if __name__ == '__main__': main()
